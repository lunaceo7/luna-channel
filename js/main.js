function renderArchiveTimeline(list) {
  const timelineEl = $("#archive-timeline");
  if (!timelineEl) return;
  if (!list.length) {
    timelineEl.innerHTML = `<div class="empty-state">該当するセミナーがありません。</div>`;
    return;
  }
  let html = "";
  let currentYear = null;
  const seenMonths = {};

  list.forEach(s => {
    const d = new Date(s.date + "T00:00:00");
    const year = d.getFullYear();
    const monthKey = `${year}-${String(d.getMonth() + 1).padStart(2, "0")}`;
    const monthLabel = `${year}年${MONTH_LABEL[d.getMonth()]}`;

    if (year !== currentYear) {
      if (currentYear !== null) html += `</div></div>`;
      html += `<div class="archive-year"><div class="archive-year-label">${year}年</div><div class="archive-year-body">`;
      currentYear = year;
    }
    if (!seenMonths[monthKey]) {
      seenMonths[monthKey] = true;
      html += `<div class="archive-month-label">${s.dateLabel ? s.dateLabel : monthLabel}</div>`;
    }
    html += timelineItemHTML(s);
  });
  if (currentYear !== null) html += `</div></div>`;
  timelineEl.innerHTML = html;
}

// 同義語は表示タグを増やさず、検索語として受け付ける。
const ARCHIVE_SEARCH_ALIASES = {
  "生成AI": "AI活用 ChatGPT AI入門", "起業・副業": "起業 副業",
  "Kindle出版": "Kindle 電子書籍", "仕事効率化": "生産性 業務改善",
  "コミュニケーション": "話し方 対人関係", "動画制作": "動画編集 AI動画"
};
function normalizeArchiveQuery(value) {
  return String(value || "").normalize("NFKC").toLocaleLowerCase("ja");
}
function filterArchiveSeminars(list, {query = "", category = "", tag = ""} = {}) {
  const terms = normalizeArchiveQuery(query).trim().split(/\s+/).filter(Boolean);
  return list.filter(s => {
    if (category && s.category !== category) return false;
    if (tag && !(s.tags || []).includes(tag)) return false;
    const sp = getSpeaker(s.speakerId);
    const haystack = normalizeArchiveQuery([
      s.title, s.subtitle, s.desc, ...(s.longDesc || []), s.category,
      ...(s.tags || []), ...(s.tags || []).map(t => ARCHIVE_SEARCH_ALIASES[t] || ""),
      sp?.name, sp?.alias, s.guestNote, s.date
    ].filter(Boolean).join(" "));
    return terms.every(term => haystack.includes(term));
  });
}
function initArchivePage() {
  const list = pastSeminarsChronological();
  const search = $("#archive-search");
  const category = $("#archive-category");
  const tag = $("#archive-tag");
  const reset = $("#archive-reset");
  const addOption = (select, value) => {
    const option = document.createElement("option");
    option.value = value;
    option.textContent = value;
    select.append(option);
  };
  [...new Set(list.map(s => s.category))].forEach(c => addOption(category, c));
  const usedTags = new Set(list.flatMap(s => s.tags || []));
  [...COMMON_SEMINAR_TAGS, ...SPECIALIST_SEMINAR_TAGS].filter(t => usedTags.has(t))
    .forEach(t => addOption(tag, t));
  const render = () => {
    const filtered = filterArchiveSeminars(list, {query: search.value, category: category.value, tag: tag.value});
    renderArchiveTimeline(filtered);
    setText("#archive-results", `${filtered.length}件 / 全${list.length}件`);
    reset.disabled = !search.value && !category.value && !tag.value;
  };
  search.addEventListener("input", render);
  category.addEventListener("change", render);
  tag.addEventListener("change", render);
  reset.addEventListener("click", () => {
    search.value = ""; category.value = ""; tag.value = "";
    render(); search.focus();
  });
  $("#archive-timeline").addEventListener("click", e => {
    const button = e.target.closest(".archive-tag");
    if (!button) return;
    tag.value = button.dataset.tag;
    render();
    tag.focus();
    $("#archive-filters").scrollIntoView({behavior: "smooth", block: "start"});
  });
  render();
  setText("#archive-count", `${totalSessionCount()}回`);
}

